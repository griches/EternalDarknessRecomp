#!/usr/bin/env python3
"""Build the guest symbol table for the host's intercepts from the user's main.dol.

The names come from the unending-occlusion decomp's map for the USA disc
(config/GEDE01/symbols.txt, CC0). On a USA DOL they are used as they are. On
any other build (the PAL GEDP01 disc) each function is carried over by
following the shift between the two builds, which changes only slowly: a USA
function lands where the shifted address starts a function, ends one with
blr/b/rfi at its size, and the next two functions agree.

usage: symbols.py <symbols.txt> <main.dol> <out-dir>
writes <out-dir>/sdk_symbols.inc (named functions, address-sorted) and
<out-dir>/symbols.tsv (name, USA address, address in this DOL)
"""
import collections
import os
import re
import struct
import sys

USA_DOL_SIZE = 3156384
SYMBOL_RE = re.compile(
    r"^(\S+)\s*=\s*\.text:0x([0-9A-Fa-f]+);.*type:function size:0x([0-9A-Fa-f]+)")
UNNAMED_RE = re.compile(r"^(fn|func|lbl|sub|FUN)_[0-9A-Fa-f]+$")


def read_text_words(dol):
    offs = struct.unpack(">18I", dol[0:72])
    addrs = struct.unpack(">18I", dol[72:144])
    sizes = struct.unpack(">18I", dol[144:216])
    words = {}
    for o, b, s in zip(offs[:7], addrs[:7], sizes[:7]):
        for i in range(0, s, 4):
            words[b + i] = struct.unpack(">I", dol[o + i:o + i + 4])[0]
    return words


def is_end(w):
    return w in (0x4E800020, 0x4C000064) or ((w >> 26) == 18 and not (w & 1))


def track(usa, words):
    def boundary(a):
        p, w = words.get(a - 4), words.get(a)
        return w is not None and w != 0 and (p is None or p == 0 or is_end(p))

    def fits(a, s):
        end = a + s
        return (boundary(a) and end - 4 in words and is_end(words[end - 4])
                and (end not in words or words[end] == 0 or boundary(end)))

    shift, out = 0, []
    for i, (a, s, n) in enumerate(usa):
        def score(d):
            if not fits(a + d, s):
                return 0
            return 1 + sum(1 for j in (1, 2)
                           if i + j < len(usa) and fits(usa[i + j][0] + d, usa[i + j][1]))
        best = shift if score(shift) >= 2 else None
        step = 4
        while best is None and step < 0x2000:
            for d in (shift + step, shift - step):
                if score(d) == 3:
                    best = d
                    break
            step += 4
        if best is not None:
            shift = best
            out.append((n, a, a + best))
    return out


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    symbols_path, dol_path, out_dir = sys.argv[1:]
    dol = open(dol_path, "rb").read()
    usa = sorted((int(m.group(2), 16), int(m.group(3), 16), m.group(1))
                 for m in map(SYMBOL_RE.match, open(symbols_path)) if m)

    if len(dol) == USA_DOL_SIZE:
        mapped = [(n, a, a) for a, _s, n in usa]
    else:
        mapped = track(usa, read_text_words(dol))

    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "symbols.tsv"), "w") as f:
        for n, a, p in mapped:
            f.write(f"{n}\t{a:08x}\t{p:08x}\n")

    seen, named = set(), []
    for n, _a, p in mapped:
        if UNNAMED_RE.match(n) or n in seen:
            continue
        seen.add(n)
        named.append((p, n))
    named.sort()
    with open(os.path.join(out_dir, "sdk_symbols.inc"), "w") as f:
        f.write("// Generated by tools/symbols.py from the user's main.dol -- do not edit.\n")
        f.write(f"// {len(named)} named functions of {len(usa)} in the decomp map.\n\n")
        for p, n in named:
            f.write(f'    {{ 0x{p:08X}u, "{n}" }},\n')

    shifts = collections.Counter(p - a for _n, a, p in mapped)
    print(f"symbols.py: {len(mapped)}/{len(usa)} functions placed, "
          f"{len(named)} named, {len(shifts)} distinct shifts")


if __name__ == "__main__":
    main()
